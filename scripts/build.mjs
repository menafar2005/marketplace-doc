// Build: content/*.md + spec/* → src/generated/content.js
// ریپو منبع حقیقت است؛ هر deploy دوباره از همین فایل‌ها ساخته می‌شود.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { execSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createMarked, extractToc, plainText } from "./lib/markdown.mjs";
import { groupMarkdown, groupHtml, groupToc } from "./lib/api-pages.mjs";
import { groups, baseUrl } from "../spec/endpoints.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const platform = JSON.parse(readFileSync(join(root, "spec/platform.json"), "utf8"));
const marked = createMarked();

function parseFrontmatter(raw, file) {
  const m = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(raw);
  if (!m) throw new Error(`${file}: frontmatter missing`);
  const meta = {};
  for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  for (const k of ["title", "section", "order", "lead"]) {
    if (!meta[k]) throw new Error(`${file}: frontmatter "${k}" missing`);
  }
  return { meta: { ...meta, order: Number(meta.order) }, body: m[2].replace(/^\n+/, "") };
}

const mdTable = (head, rows) =>
  [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");

const injections = {
  "<!--STATUS_TABLE-->": mdTable(
    ["Status", "معنی", "رفتار پیشنهادی"],
    platform.httpStatuses.map((s) => [`\`${s.status}\``, s.meaning, s.action])
  ),
  "<!--ERROR_TABLE-->": mdTable(
    ["کد", "توضیح"],
    platform.errorCodes.map((e) => [`\`${e.code}\``, e.meaning])
  ),
};

const pages = [];

// ---- صفحه‌های دستی ----
const contentDir = join(root, "content");
for (const file of readdirSync(contentDir).filter((f) => f.endsWith(".md")).sort()) {
  const slug = file.replace(/\.md$/, "");
  const { meta, body } = parseFrontmatter(readFileSync(join(contentDir, file), "utf8"), file);
  let md = body;
  for (const [marker, value] of Object.entries(injections)) md = md.replace(marker, value);
  pages.push({
    slug,
    type: slug === "build-with-mcp" ? "mcp" : "guide",
    title: meta.title,
    section: meta.section,
    order: meta.order,
    lead: meta.lead,
    description: meta.description || meta.lead,
    md,
    html: marked.parse(md),
    toc: extractToc(md, marked),
  });
}

// ---- صفحه‌های مرجع API (از spec) ----
groups.forEach((g, i) => {
  const md = groupMarkdown(g);
  pages.push({
    slug: g.page,
    type: "api",
    title: `API ${g.title}`,
    section: "reference",
    order: 7 + i,
    lead: g.intro,
    description: g.intro,
    md,
    html: groupHtml(g),
    toc: groupToc(g),
  });
});

pages.sort((a, b) => (a.section === b.section ? a.order - b.order : a.section === "start" ? -1 : 1));

// ---- ایندکس جستجو: یک chunk به‌ازای هر h2 ----
const search = [];
for (const p of pages) {
  const parts = p.md.split(/\n(?=## )/);
  parts.forEach((part, i) => {
    const hm = /^## (.+?)(?:\s*\{#([\w-]+)\})?\s*$/m.exec(part);
    const heading = i === 0 && !part.startsWith("## ") ? p.title : hm ? hm[1] : p.title;
    const id = i === 0 && !part.startsWith("## ") ? "" : hm?.[2] || "";
    const text = plainText(part);
    if (text) search.push({ slug: p.slug, page: p.title, heading, id, text });
  });
}

// ---- نسخه: commit همان push که deploy را ساخته ----
function git(cmd) {
  try {
    return execSync(cmd, { cwd: root, stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch {
    return "";
  }
}
const commit = process.env.GITHUB_SHA || git("git rev-parse HEAD") || "dev";
const meta = {
  commit,
  shortCommit: commit.slice(0, 7),
  message: process.env.DOCS_COMMIT_MESSAGE || git("git log -1 --pretty=%s") || "",
  builtAt: new Date().toISOString(),
  pageCount: pages.length,
};

const out = `// GENERATED by scripts/build.mjs — do not edit.\n` +
  `export const pages = ${JSON.stringify(pages)};\n` +
  `export const search = ${JSON.stringify(search)};\n` +
  `export const spec = ${JSON.stringify({ baseUrl, groups, platform })};\n` +
  `export const meta = ${JSON.stringify(meta)};\n`;

mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(join(root, "src/generated/content.js"), out);
console.log(`built ${pages.length} pages, ${search.length} search chunks @ ${meta.shortCommit}`);
